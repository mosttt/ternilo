import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { createRequire } from 'node:module'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const require = createRequire(import.meta.url)
const packageFile = require.resolve('katex/package.json')
const katexRoot = path.dirname(packageFile)
const { version } = JSON.parse(await readFile(packageFile, 'utf8'))
const root = fileURLToPath(new URL('../../', import.meta.url))
const assets = path.join(root, 'crates/ternilo-builtins/assets')
await mkdir(assets, { recursive: true })
const source = await readFile(path.join(katexRoot, 'dist/katex.min.js'), 'utf8')
await writeFile(path.join(assets, 'document-math.js'), `// KaTeX ${version}; MIT license: licenses/katex.MIT. Generated by web/scripts/build-document-math.mjs.\n${source}\n`)
let css = await readFile(path.join(katexRoot, 'dist/katex.min.css'), 'utf8')
for (const match of [...css.matchAll(/src:([^;}]+)/g)]) {
  const font = match[1].match(/url\((fonts\/[^)]+\.woff2)\)/)?.[1]
  if (!font) throw new Error(`KaTeX font has no WOFF2 source: ${match[0]}`)
  const data = (await readFile(path.join(katexRoot, 'dist', font))).toString('base64')
  css = css.replace(match[0], `src:url(data:font/woff2;base64,${data}) format("woff2")`)
}
await writeFile(path.join(assets, 'document-math.css'), `/* KaTeX ${version}; MIT license: licenses/katex.MIT. Generated by web/scripts/build-document-math.mjs. */\n${css}\n`)
await writeFile(path.join(root, 'licenses/katex.MIT'), await readFile(path.join(katexRoot, 'LICENSE')))
